"""تحويل التاريخ الميلادي إلى هجري — مسار احتياطي على الخادم.

المصدر الأساسي في التطبيق هو المتصفح (Intl بتقويم islamic-umalqura).
هذا الملف يطبّق «التقويم الهجري الجدولي/الحسابي» (دورة 30 سنة) وقد يختلف
يوماً واحداً عن تقويم أم القرى الرسمي، ولذلك يوسَم مصدره بوضوح.
"""
import datetime as _dt

MONTHS = ["محرم", "صفر", "ربيع الأول", "ربيع الآخر", "جمادى الأولى", "جمادى الآخرة",
          "رجب", "شعبان", "رمضان", "شوال", "ذو القعدة", "ذو الحجة"]

SOURCE_TABULAR = "تحويل حسابي تقريبي (التقويم الهجري الجدولي) — قد يختلف يوماً عن تقويم أم القرى؛ يحتاج تأكيد"
SOURCE_BROWSER = "تقويم أم القرى عبر محرك Intl في المتصفح (بيانات ICU/CLDR)"
SOURCE_MANUAL = "إدخال يدوي"


def tabular(iso_date: str):
    """يعيد (يوم، شهر، سنة) هجرية حسابية لتاريخ ميلادي ISO."""
    d = _dt.date.fromisoformat(iso_date)
    jd = d.toordinal() + 1721425  # رقم اليوم اليولياني
    l = jd - 1948440 + 10632
    n = (l - 1) // 10631
    l = l - 10631 * n + 354
    j = ((10985 - l) // 5316) * ((50 * l) // 17719) + (l // 5670) * ((43 * l) // 15238)
    l = l - ((30 - j) // 15) * ((17719 * j) // 50) - (j // 16) * ((15238 * j) // 43) + 29
    m = (24 * l) // 709
    day = l - (709 * m) // 24
    y = 30 * n + j - 30
    return day, m, y


def tabular_text(iso_date: str) -> str:
    day, m, y = tabular(iso_date)
    return f"{day} {MONTHS[m - 1]} {y} هـ"
